// Turns the subject illustrations into path data for `Vector`, which draws them the same on iOS,
// Android and the web without an SVG loader in Metro or Vite. The sources are the landing page's
// files in apps/web/public/subjects. After adding or changing one, run `vp run art:generate`.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

const root = NodePath.resolve(import.meta.dirname, "../..");
const sources = NodePath.join(root, "apps/web/public/subjects");
const target = NodePath.join(root, "packages/domain-ui/src/subject/SubjectDrawings.ts");

interface Filled {
  readonly d: string;
  readonly fill: string;
}

const attribute = (attributes: string, name: string) =>
  new RegExp(`(?:^|\\s)${name}="([^"]*)"`, "u").exec(attributes)?.[1];

/** The element's own fill, from the attribute or its style. */
const fillOf = (attributes: string) =>
  attribute(attributes, "fill") ??
  /fill:\s*([^;"]+)/u.exec(attribute(attributes, "style") ?? "")?.[1];

const number = (attributes: string, name: string) => Number(attribute(attributes, name) ?? 0);

const round = (value: number) => String(Math.round(value * 100) / 100);

/** A point through the element's `matrix(a b c d e f)`, when it has one. */
function placed(attributes: string) {
  const matrix = /matrix\(([^)]*)\)/u.exec(attribute(attributes, "transform") ?? "")?.[1];

  const [a = 1, b = 0, c = 0, d = 1, e = 0, f = 0] =
    matrix
      ?.trim()
      .split(/[\s,]+/u)
      .map(Number) ?? [];

  return (x: number, y: number) => `${round(a * x + c * y + e)} ${round(b * x + d * y + f)}`;
}

function outline(tag: string, attributes: string): string | undefined {
  const at = placed(attributes);

  switch (tag) {
    case "path":
      return attribute(attributes, "d")?.replaceAll(/\s+/gu, " ").trim();
    case "circle": {
      const cx = number(attributes, "cx");
      const cy = number(attributes, "cy");
      const r = number(attributes, "r");
      const arc = `a${round(r)} ${round(r)} 0 1 0`;

      return `M${round(cx - r)} ${round(cy)}${arc} ${round(2 * r)} 0${arc} ${round(-2 * r)} 0Z`;
    }

    case "rect": {
      const x = number(attributes, "x");
      const y = number(attributes, "y");
      const width = number(attributes, "width");
      const height = number(attributes, "height");

      return `M${at(x, y)}L${at(x + width, y)}L${at(x + width, y + height)}L${at(x, y + height)}Z`;
    }

    case "polygon": {
      const points = (attribute(attributes, "points") ?? "")
        .trim()
        .split(/[\s,]+/u)
        .map(Number);

      const pairs = points.flatMap((x, index) =>
        index % 2 === 0 ? [at(x, points[index + 1] ?? 0)] : [],
      );

      return `M${pairs.join("L")}Z`;
    }

    default:
      return undefined;
  }
}

function convert(svg: string) {
  const filled: Array<Filled> = [];
  // The fill each open group hands down to its children.
  const inherited: Array<string | undefined> = [];
  let viewBox = "0 0 512 512";

  for (const [, closing, tag, attributes = "", selfClosing] of svg.matchAll(
    /<(\/?)([a-zA-Z]+)((?:\s[^>]*?)?)(\/?)>/gsu,
  )) {
    if (tag === "svg" && closing === "") viewBox = attribute(attributes, "viewBox") ?? viewBox;

    if (tag === "g") {
      if (closing === "/") inherited.pop();
      else if (selfClosing === "") inherited.push(fillOf(attributes) ?? inherited.at(-1));

      // Latin's one group shift, as a shift of the view box the other way.
      const shift = /translate\(0 (-?\d+)\)/u.exec(attributes)?.[1];

      if (shift !== undefined) {
        const [x = 0, y = 0, width = 0, height = 0] = viewBox.split(" ").map(Number);
        viewBox = [x, y - Number(shift), width, height].join(" ");
      }

      continue;
    }

    const d = closing === "" && tag !== undefined ? outline(tag, attributes) : undefined;
    const fill = fillOf(attributes) ?? inherited.at(-1) ?? "#000000";

    if (d !== undefined && fill !== "none") filled.push({ d, fill: fill.toUpperCase() });
  }

  return { viewBox, filled };
}

const names = NodeFS.readdirSync(sources)
  .filter((file) => file.endsWith(".svg"))
  .map((file) => NodePath.basename(file, ".svg"))
  .sort();

const drawings = names.map((name) => {
  const { viewBox, filled } = convert(
    NodeFS.readFileSync(NodePath.join(sources, `${name}.svg`), "latin1"),
  );

  const paths = filled.map(
    ({ d, fill }) => `      { d: ${JSON.stringify(d)}, fill: ${JSON.stringify(fill)} },`,
  );

  return `  ${name}: {\n    viewBox: ${JSON.stringify(viewBox)},\n    paths: [\n${paths.join("\n")}\n    ],\n  },`;
});

NodeFS.writeFileSync(
  target,
  `// Generated by tools/subject-art/generate.ts from apps/web/public/subjects. Don't edit it by hand:
// change the SVG and run \`vp run art:generate\`.
export * as SubjectDrawings from "./SubjectDrawings.ts";

/** A subject's illustration as filled paths, which \`Vector\` draws. */
export interface Drawing {
  readonly viewBox: string;
  readonly paths: ReadonlyArray<{ readonly d: string; readonly fill: string }>;
}

export type Name = ${names.map((name) => JSON.stringify(name)).join(" | ")};

export const drawings: Readonly<Record<Name, Drawing>> = {
${drawings.join("\n")}
};
`,
);
